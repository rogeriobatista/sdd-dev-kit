import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type {
  CanonicalDocument,
  CanonicalScenario,
  SddManifest,
} from "@rogeriobatista/core";
import {
  resolveSddPath,
  slugifyScenarioBase,
  usesCucumber,
  usesPlaywright,
} from "@rogeriobatista/core";

export interface MaterializeResult {
  e2eFiles: string[];
  unitFiles: string[];
}

/** Playwright spec generation aligned with adapter-ts patterns. */
function toPlaywrightSpec(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `import { test, expect } from "@playwright/test";`,
    ``,
    `// Generated by @rogeriobatista/adapter-react-vite from ${doc.sourceFile}`,
    ``,
  ];
  for (const scenario of scenarios) {
    lines.push(
      `test(${JSON.stringify(scenario.title)}, async ({ page }) => {`,
      `  // Intention: ${doc.intention ?? scenario.intention ?? "n/a"}`,
      `  // Steps:`,
    );
    for (const step of scenario.steps) {
      lines.push(`  // ${step.keyword} ${step.text}`);
    }
    lines.push(
      `  await page.goto("/");`,
      `  // TODO: drive UI per steps above`,
      `  await expect(page.locator("body")).toBeVisible();`,
      `});`,
      ``,
    );
  }
  return lines.join("\n");
}

function toVitestStub(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `import { describe, it, expect } from "vitest";`,
    ``,
    `// Generated by @rogeriobatista/adapter-react-vite from ${doc.sourceFile}`,
    ``,
    `describe(${JSON.stringify(doc.featureTitle)}, () => {`,
  ];
  for (const scenario of scenarios) {
    lines.push(`  it(${JSON.stringify(scenario.title)}, () => {`);
    for (const step of scenario.steps) {
      lines.push(`    // ${step.keyword} ${step.text}`);
    }
    lines.push(
      `    expect.fail("not implemented: ${scenario.id}");`,
      `  });`,
      ``,
    );
  }
  lines.push(`});`, ``);
  return lines.join("\n");
}

export async function materializeCanonical(
  projectRoot: string,
  manifest: SddManifest,
  documents: CanonicalDocument[],
): Promise<MaterializeResult> {
  const e2eDir = resolveSddPath(projectRoot, manifest.paths.e2e);
  const unitDir = resolveSddPath(projectRoot, "tests/unit");
  await mkdir(e2eDir, { recursive: true });
  await mkdir(unitDir, { recursive: true });

  const result: MaterializeResult = { e2eFiles: [], unitFiles: [] };

  for (const doc of documents) {
    const base = slugifyScenarioBase(
      path.basename(doc.sourceFile, path.extname(doc.sourceFile)),
    );
    const ui = doc.scenarios.filter(usesPlaywright);
    const api = doc.scenarios.filter(usesCucumber);

    if (ui.length > 0) {
      const e2ePath = path.join(e2eDir, `${base}.spec.ts`);
      await writeFile(e2ePath, toPlaywrightSpec(doc, ui), "utf8");
      result.e2eFiles.push(e2ePath);
    }
    if (api.length > 0) {
      const unitPath = path.join(unitDir, `${base}.test.ts`);
      await writeFile(unitPath, toVitestStub(doc, api), "utf8");
      result.unitFiles.push(unitPath);
    }
  }
  return result;
}
