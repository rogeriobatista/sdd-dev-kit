import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type {
  CanonicalDocument,
  CanonicalScenario,
  SddManifest,
} from "@sdd-dev-kit/core";
import {
  formatGherkinTags,
  resolveSddPath,
  slugifyScenarioBase,
  usesCucumber,
} from "@sdd-dev-kit/core";

export interface MaterializeResult {
  featureFiles: string[];
  stepFiles: string[];
  unitFiles: string[];
}

function toFeatureContent(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `# language: pt`,
    `Funcionalidade: ${doc.featureTitle}`,
    ``,
  ];
  for (const scenario of scenarios) {
    const tags = formatGherkinTags(scenario.tags);
    if (tags) lines.push(`  ${tags}`);
    lines.push(`  Cenário: ${scenario.title}`);
    for (const step of scenario.steps) {
      lines.push(`    ${step.keyword} ${step.text}`);
    }
    lines.push(``);
  }
  return lines.join("\n");
}

function toStepStub(scenarios: CanonicalScenario[]): string {
  const seen = new Set<string>();
  const lines: string[] = [
    `import { Given, When, Then } from "@cucumber/cucumber";`,
    ``,
    `// Generated by @sdd-dev-kit/adapter-node-graphql`,
    ``,
  ];
  const keywordMap: Record<string, "Given" | "When" | "Then"> = {
    Dado: "Given",
    Quando: "When",
    Então: "Then",
    E: "Given",
  };
  for (const scenario of scenarios) {
    for (const step of scenario.steps) {
      const key = `${step.keyword}|${step.text}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const fn = keywordMap[step.keyword] ?? "Given";
      const escaped = step.text.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
      lines.push(
        `${fn}("${escaped}", async function () {`,
        `  throw new Error("Step not implemented: ${escaped}");`,
        `});`,
        ``,
      );
    }
  }
  return lines.join("\n");
}

function toVitestStub(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `import { describe, it, expect } from "vitest";`,
    ``,
    `// GraphQL API scenarios from ${doc.sourceFile}`,
    ``,
    `describe(${JSON.stringify(doc.featureTitle)}, () => {`,
  ];
  for (const scenario of scenarios) {
    lines.push(`  it(${JSON.stringify(scenario.title)}, async () => {`);
    for (const step of scenario.steps) {
      lines.push(`    // ${step.keyword} ${step.text}`);
    }
    lines.push(
      `    // TODO: execute GraphQL operation against the local schema`,
      `    expect.fail("not implemented: ${scenario.id}");`,
      `  });`,
      ``,
    );
  }
  lines.push(`});`, ``);
  return lines.join("\n");
}

export async function materializeCanonical(
  projectRoot: string,
  manifest: SddManifest,
  documents: CanonicalDocument[],
): Promise<MaterializeResult> {
  const featuresDir = resolveSddPath(projectRoot, manifest.paths.features);
  const stepsDir = resolveSddPath(projectRoot, manifest.paths.steps);
  const unitDir = resolveSddPath(projectRoot, "tests/unit");
  await mkdir(featuresDir, { recursive: true });
  await mkdir(stepsDir, { recursive: true });
  await mkdir(unitDir, { recursive: true });

  const result: MaterializeResult = {
    featureFiles: [],
    stepFiles: [],
    unitFiles: [],
  };

  for (const doc of documents) {
    const base = slugifyScenarioBase(
      path.basename(doc.sourceFile, path.extname(doc.sourceFile)),
    );
    const api = doc.scenarios.filter(usesCucumber);
    if (api.length === 0) continue;

    const featurePath = path.join(featuresDir, `${base}.feature`);
    await writeFile(featurePath, toFeatureContent(doc, api), "utf8");
    result.featureFiles.push(featurePath);

    const stepPath = path.join(stepsDir, `${base}.steps.ts`);
    await writeFile(stepPath, toStepStub(api), "utf8");
    result.stepFiles.push(stepPath);

    const unitPath = path.join(unitDir, `${base}.test.ts`);
    await writeFile(unitPath, toVitestStub(doc, api), "utf8");
    result.unitFiles.push(unitPath);
  }
  return result;
}
