import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { CanonicalDocument, CanonicalScenario, SddManifest } from "@rogeriobatista/core";
import {
  formatGherkinTags,
  resolveSddPath,
  slugifyScenarioBase,
  usesCucumber,
  usesPlaywright,
} from "@rogeriobatista/core";

export interface MaterializeResult {
  featureFiles: string[];
  stepFiles: string[];
  e2eFiles: string[];
}

function toFeatureContent(doc: CanonicalDocument, scenarios: CanonicalScenario[]): string {
  const lines: string[] = [`# language: pt`, `Funcionalidade: ${doc.featureTitle}`, ``];
  if (doc.intention) {
    lines.push(`  # Intenção: ${doc.intention.replace(/\n/g, " ")}`, ``);
  }
  for (const scenario of scenarios) {
    const tags = formatGherkinTags(scenario.tags);
    if (tags) lines.push(`  ${tags}`);
    lines.push(`  Cenário: ${scenario.title}`);
    for (const step of scenario.steps) {
      lines.push(`    ${step.keyword} ${step.text}`);
    }
    lines.push(``);
  }
  return lines.join("\n");
}

function toStepStub(scenarios: CanonicalScenario[]): string {
  const seen = new Set<string>();
  const lines: string[] = [
    `import { Given, When, Then } from "@cucumber/cucumber";`,
    ``,
    `// Generated by @rogeriobatista/adapter-ts — regenerate via /sdd run (executable phase).`,
    `// Implement domain assertions; do not hand-edit structure.`,
    ``,
  ];

  const keywordMap: Record<string, "Given" | "When" | "Then"> = {
    Dado: "Given",
    Quando: "When",
    Então: "Then",
    E: "Given",
  };

  for (const scenario of scenarios) {
    for (const step of scenario.steps) {
      const key = `${step.keyword}|${step.text}`;
      if (seen.has(key)) continue;
      seen.add(key);
      const fn = keywordMap[step.keyword] ?? "Given";
      const escaped = step.text.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
      lines.push(
        `${fn}("${escaped}", async function () {`,
        `  // TODO: implement — scenario ${scenario.id}`,
        `  throw new Error("Step not implemented: ${escaped}");`,
        `});`,
        ``,
      );
    }
  }
  return lines.join("\n");
}

function toPlaywrightSpec(doc: CanonicalDocument, scenarios: CanonicalScenario[]): string {
  const lines: string[] = [
    `import { test, expect } from "@playwright/test";`,
    ``,
    `// Generated by @rogeriobatista/adapter-ts from ${doc.sourceFile}`,
    ``,
  ];
  for (const scenario of scenarios) {
    lines.push(
      `test(${JSON.stringify(scenario.title)}, async ({ page }) => {`,
      `  // Intention: ${doc.intention ?? scenario.intention ?? "n/a"}`,
      `  // Steps:`,
    );
    for (const step of scenario.steps) {
      lines.push(`  // ${step.keyword} ${step.text}`);
    }
    lines.push(
      `  await page.goto("/");`,
      `  // TODO: drive UI per steps above`,
      `  await expect(page.locator("body")).toBeVisible();`,
      `});`,
      ``,
    );
  }
  return lines.join("\n");
}

export async function materializeCanonical(
  projectRoot: string,
  manifest: SddManifest,
  documents: CanonicalDocument[],
): Promise<MaterializeResult> {
  const featuresDir = resolveSddPath(projectRoot, manifest.paths.features);
  const stepsDir = resolveSddPath(projectRoot, manifest.paths.steps);
  const e2eDir = resolveSddPath(projectRoot, manifest.paths.e2e);

  await mkdir(featuresDir, { recursive: true });
  await mkdir(stepsDir, { recursive: true });
  await mkdir(e2eDir, { recursive: true });

  const result: MaterializeResult = {
    featureFiles: [],
    stepFiles: [],
    e2eFiles: [],
  };

  for (const doc of documents) {
    const base = slugifyScenarioBase(
      path.basename(doc.sourceFile, path.extname(doc.sourceFile)),
    );
    const cucumberScenarios = doc.scenarios.filter(usesCucumber);
    const playwrightScenarios = doc.scenarios.filter(usesPlaywright);

    if (cucumberScenarios.length > 0) {
      const featurePath = path.join(featuresDir, `${base}.feature`);
      await writeFile(featurePath, toFeatureContent(doc, cucumberScenarios), "utf8");
      result.featureFiles.push(featurePath);

      const stepPath = path.join(stepsDir, `${base}.steps.ts`);
      await writeFile(stepPath, toStepStub(cucumberScenarios), "utf8");
      result.stepFiles.push(stepPath);
    }

    if (playwrightScenarios.length > 0) {
      const e2ePath = path.join(e2eDir, `${base}.spec.ts`);
      await writeFile(e2ePath, toPlaywrightSpec(doc, playwrightScenarios), "utf8");
      result.e2eFiles.push(e2ePath);
    }
  }

  return result;
}
