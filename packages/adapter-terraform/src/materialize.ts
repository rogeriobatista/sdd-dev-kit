import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type {
  CanonicalDocument,
  CanonicalScenario,
  SddManifest,
} from "@rogeriobatista/core";
import { resolveSddPath, slugifyScenarioBase } from "@rogeriobatista/core";

export interface MaterializeResult {
  testFiles: string[];
}

function toTftest(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `# Generated by @rogeriobatista/adapter-terraform from ${doc.sourceFile}`,
    `# NL scenarios map to terraform test assertions (no cloud apply).`,
    ``,
  ];
  for (const scenario of scenarios) {
    const name = slugifyScenarioBase(scenario.title).replace(/-/g, "_") || "scenario";
    lines.push(`run "${name}" {`);
    lines.push(`  command = plan`);
    lines.push(``);
    lines.push(`  # Scenario: ${scenario.title}`);
    for (const step of scenario.steps) {
      lines.push(`  # ${step.keyword} ${step.text}`);
    }
    lines.push(``);
    lines.push(`  assert {`);
    lines.push(`    condition     = true`);
    lines.push(
      `    error_message = "TODO implement assertion for ${scenario.id}"`,
    );
    lines.push(`  }`);
    lines.push(`}`);
    lines.push(``);
  }
  return lines.join("\n");
}

export async function materializeCanonical(
  projectRoot: string,
  _manifest: SddManifest,
  documents: CanonicalDocument[],
): Promise<MaterializeResult> {
  const testsDir = resolveSddPath(projectRoot, "tests");
  await mkdir(testsDir, { recursive: true });
  const result: MaterializeResult = { testFiles: [] };

  for (const doc of documents) {
    const base = slugifyScenarioBase(
      path.basename(doc.sourceFile, path.extname(doc.sourceFile)),
    );
    const filePath = path.join(testsDir, `${base}.tftest.hcl`);
    await writeFile(filePath, toTftest(doc, doc.scenarios), "utf8");
    result.testFiles.push(filePath);
  }
  return result;
}
