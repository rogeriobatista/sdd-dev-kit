import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type {
  CanonicalDocument,
  CanonicalScenario,
  SddManifest,
} from "@sdd-dev-kit/core";
import {
  resolveSddPath,
  slugifyScenarioBase,
  usesPlaywright,
} from "@sdd-dev-kit/core";

export interface MaterializeResult {
  testFiles: string[];
}

function toPytestModule(
  doc: CanonicalDocument,
  scenarios: CanonicalScenario[],
): string {
  const lines: string[] = [
    `"""Generated by @sdd-dev-kit/adapter-python from ${doc.sourceFile}."""`,
    `import pytest`,
    ``,
  ];
  for (const scenario of scenarios) {
    const fn = slugifyScenarioBase(scenario.title).replace(/-/g, "_") || "scenario";
    const ui = usesPlaywright(scenario);
    if (ui) {
      lines.push(`@pytest.mark.ui`);
    }
    lines.push(`def test_${fn}():`);
    lines.push(`    """${scenario.title}"""`);
    for (const step of scenario.steps) {
      lines.push(`    # ${step.keyword} ${step.text}`);
    }
    lines.push(`    pytest.fail("Step not implemented: ${scenario.id}")`);
    lines.push(``);
  }
  return lines.join("\n");
}

export async function materializeCanonical(
  projectRoot: string,
  _manifest: SddManifest,
  documents: CanonicalDocument[],
): Promise<MaterializeResult> {
  const testsDir = resolveSddPath(projectRoot, "tests");
  await mkdir(testsDir, { recursive: true });
  const result: MaterializeResult = { testFiles: [] };

  for (const doc of documents) {
    const base = slugifyScenarioBase(
      path.basename(doc.sourceFile, path.extname(doc.sourceFile)),
    );
    const filePath = path.join(testsDir, `test_${base.replace(/-/g, "_")}.py`);
    await writeFile(filePath, toPytestModule(doc, doc.scenarios), "utf8");
    result.testFiles.push(filePath);
  }
  return result;
}
